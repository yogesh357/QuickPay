"use client";

import { useEffect, useState } from "react";
import { useRouter } from "next/navigation";
import DashboardSidebar from "@/components/DashboardSidebar";
import DashboardHeader from "@/components/DashboardHeader";
import {
  apiGetProfile,
  apiUpdateSettings,
  Merchant,
  getStoredToken,
  setStoredMerchant,
} from "@/lib/api";
import {
  Building2,
  QrCode,
  CheckCircle2,
  AlertCircle,
  Save,
  HelpCircle,
  ShieldAlert,
} from "lucide-react";

export default function MerchantSettingsPage() {
  const router = useRouter();
  const [merchant, setMerchant] = useState<Merchant | null>(null);
  const [businessName, setBusinessName] = useState("");
  const [upiId, setUpiId] = useState("");
  const [loading, setLoading] = useState(true);
  const [saving, setSaving] = useState(false);
  const [successMsg, setSuccessMsg] = useState<string | null>(null);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  useEffect(() => {
    const token = getStoredToken();
    if (!token) {
      router.push("/login");
      return;
    }

    async function loadProfile() {
      try {
        const data = await apiGetProfile();
        setMerchant(data);
        setBusinessName(data.business_name || "");
        setUpiId(data.upi_id || "");
      } catch (err: any) {
        setErrorMsg(err.message || "Failed to load merchant profile");
      } finally {
        setLoading(false);
      }
    }

    loadProfile();
  }, [router]);

  const handleSave = async (e: React.FormEvent) => {
    e.preventDefault();
    setSuccessMsg(null);
    setErrorMsg(null);
    setSaving(true);

    try {
      const updated = await apiUpdateSettings({
        business_name: businessName,
        upi_id: upiId || undefined,
      });

      setMerchant(updated);
      setStoredMerchant(updated);
      setSuccessMsg("Merchant settings updated successfully!");
      setTimeout(() => setSuccessMsg(null), 3500);
    } catch (err: any) {
      setErrorMsg(err.message || "Failed to save settings");
    } finally {
      setSaving(false);
    }
  };

  return (
    <div className="min-h-screen bg-slate-50 flex flex-col md:flex-row">
      <DashboardSidebar />

      <main className="flex-1 min-w-0 flex flex-col">
        <DashboardHeader
          merchant={merchant}
          title="Merchant Settings"
          subtitle="Configure your legal business name and destination UPI ID for receiving payments."
        />

        <div className="p-6 md:p-8 max-w-4xl space-y-6">
          {successMsg && (
            <div className="p-4 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-800 text-sm flex items-center gap-2.5 shadow-sm">
              <CheckCircle2 className="w-5 h-5 text-emerald-600 shrink-0" />
              <span>{successMsg}</span>
            </div>
          )}

          {errorMsg && (
            <div className="p-4 rounded-xl bg-rose-50 border border-rose-200 text-rose-800 text-sm flex items-center gap-2.5 shadow-sm">
              <AlertCircle className="w-5 h-5 text-rose-600 shrink-0" />
              <span>{errorMsg}</span>
            </div>
          )}

          <div className="bg-white rounded-2xl border border-slate-200 shadow-sm overflow-hidden">
            <div className="p-6 border-b border-slate-100">
              <h2 className="text-base font-bold text-slate-900">
                Payment Destination Profile
              </h2>
              <p className="text-xs text-slate-500 mt-0.5">
                These details are directly encoded into every dynamic UPI payment QR code
                generated by the QuickPay API.
              </p>
            </div>

            <form onSubmit={handleSave} className="p-6 space-y-6">
              <div>
                <label className="block text-xs font-semibold text-slate-700 uppercase tracking-wider mb-1.5">
                  Business / Store Name
                </label>
                <div className="relative">
                  <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none text-slate-400">
                    <Building2 className="w-4 h-4" />
                  </div>
                  <input
                    type="text"
                    required
                    value={businessName}
                    onChange={(e) => setBusinessName(e.target.value)}
                    placeholder="e.g. Apex Store Pvt Ltd"
                    className="w-full pl-10 pr-3.5 py-2.5 bg-slate-50 border border-slate-300 rounded-xl text-slate-900 text-sm focus:outline-none focus:border-brand-500 focus:bg-white transition"
                  />
                </div>
                <p className="text-xs text-slate-500 mt-1">
                  Appears as Payee Name (<code className="text-brand-700 font-mono">pn=...</code>) on the customer's UPI app (Google Pay, PhonePe, Paytm).
                </p>
              </div>

              <div>
                <label className="block text-xs font-semibold text-slate-700 uppercase tracking-wider mb-1.5">
                  Merchant UPI ID (VPA)
                </label>
                <div className="relative">
                  <div className="absolute inset-y-0 left-0 pl-3.5 flex items-center pointer-events-none text-slate-400">
                    <QrCode className="w-4 h-4" />
                  </div>
                  <input
                    type="text"
                    required
                    value={upiId}
                    onChange={(e) => setUpiId(e.target.value)}
                    placeholder="e.g. yourname@okhdfcbank or merchant@upi"
                    className="w-full pl-10 pr-3.5 py-2.5 bg-slate-50 border border-slate-300 rounded-xl text-slate-900 text-sm font-mono focus:outline-none focus:border-brand-500 focus:bg-white transition"
                  />
                </div>
                <p className="text-xs text-slate-500 mt-1">
                  Format must be standard Virtual Payment Address (VPA), e.g. <span className="font-mono text-slate-700">user@bank</span>. All customer payments scan directly to this handle.
                </p>
              </div>

              <div className="p-4 rounded-xl bg-slate-50 border border-slate-200 flex items-start gap-3">
                <HelpCircle className="w-5 h-5 text-brand-600 shrink-0 mt-0.5" />
                <div className="text-xs text-slate-600 space-y-1">
                  <span className="font-semibold text-slate-800">
                    Important UPI Routing Notice:
                  </span>
                  <p>
                    Ensure your UPI ID is active and enabled to receive payments. When a customer scans your QR code, payment goes directly from the customer's bank account to yours without intermediary holding accounts.
                  </p>
                </div>
              </div>

              <div className="pt-2 flex justify-end">
                <button
                  type="submit"
                  disabled={saving || loading}
                  className="inline-flex items-center gap-2 px-5 py-2.5 rounded-xl bg-brand-600 hover:bg-brand-700 text-white font-semibold text-sm transition shadow-sm disabled:opacity-50"
                >
                  <Save className="w-4 h-4" />
                  <span>{saving ? "Saving Changes..." : "Save Settings"}</span>
                </button>
              </div>
            </form>
          </div>
        </div>
      </main>
    </div>
  );
}
